CREATE TABLE CUSTOMERS (
  customer_id NUMBER PRIMARY KEY,
  name VARCHAR2(80) NOT NULL,
  city VARCHAR2(80) NOT NULL
);
CREATE TABLE ARCHIVE_CUSTOMERS (
  customer_id NUMBER PRIMARY KEY
);
CREATE TABLE ORDERS (
  order_id NUMBER PRIMARY KEY,
  customer_id NUMBER NOT NULL REFERENCES CUSTOMERS(customer_id),
  status VARCHAR2(20) NOT NULL,
  total NUMBER(10,2) NOT NULL,
  order_date DATE NOT NULL
);
CREATE TABLE PRODUCTS (
  product_id NUMBER PRIMARY KEY,
  name VARCHAR2(80) NOT NULL,
  category VARCHAR2(40) NOT NULL,
  price NUMBER(10,2) NOT NULL
);
CREATE TABLE ORDER_ITEMS (
  order_id NUMBER REFERENCES ORDERS(order_id),
  product_id NUMBER REFERENCES PRODUCTS(product_id),
  qty NUMBER NOT NULL,
  unit_price NUMBER(10,2) NOT NULL,
  CONSTRAINT pk_order_items PRIMARY KEY(order_id,product_id)
);
CREATE TABLE DEPARTMENTS (
  dept_id NUMBER PRIMARY KEY,
  dept_name VARCHAR2(80) NOT NULL
);
CREATE TABLE EMPLOYEES (
  emp_id NUMBER PRIMARY KEY,
  name VARCHAR2(80) NOT NULL,
  dept_id NUMBER REFERENCES DEPARTMENTS(dept_id),
  salary NUMBER(10,2) NOT NULL
);
CREATE TABLE PROMOTIONS (
  promotion_id NUMBER PRIMARY KEY,
  name VARCHAR2(80) NOT NULL
);
CREATE TABLE PAYMENTS (
  payment_id NUMBER PRIMARY KEY,
  customer_id NUMBER NOT NULL REFERENCES CUSTOMERS(customer_id),
  paid_at DATE NOT NULL,
  paid_amount NUMBER(10,2) NOT NULL
);
CREATE TABLE ORDER_LOG (order_id NUMBER, changed_at DATE);
CREATE TABLE PRICE_AUDIT (
  product_id NUMBER,
  old_price NUMBER(10,2),
  new_price NUMBER(10,2),
  changed_at DATE
);
CREATE TABLE STUDENTS (student_id NUMBER PRIMARY KEY, name VARCHAR2(80));
CREATE TABLE ASSESSMENTS (
  assessment_id NUMBER PRIMARY KEY,
  student_id NUMBER REFERENCES STUDENTS(student_id),
  course_id NUMBER NOT NULL,
  mark NUMBER NOT NULL,
  assessed_at DATE NOT NULL
);
CREATE TABLE VISITS (patient_id NUMBER NOT NULL, visit_date DATE NOT NULL);
CREATE TABLE INVOICES (
  invoice_id NUMBER PRIMARY KEY,
  status VARCHAR2(20) NOT NULL,
  amount NUMBER(10,2) NOT NULL
);
CREATE SEQUENCE customer_seq START WITH 100 INCREMENT BY 1;

